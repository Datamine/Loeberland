export function monsterCombat(
  level: number,
  interval: number,
  { passive = false, boss = false } = {},
) {
  return {
    level,
    hp: boss ? 20 * level : passive ? 10 * level : 5 * level + 6 * Math.max(0, level - 10),
    damage: passive ? 0 : Math.max(1, Math.round((0.9 + level * 0.28) * interval)),
    interval,
  };
}

