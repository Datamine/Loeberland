/** Template IDs are generated below from the checked-in HTML, then checked at runtime. */
export function requiredElement<T extends HTMLElement>(id: string): T {
  const value = document.getElementById(id);
  if (!value) throw new Error('Missing interface element: ' + id);
  return value as T;
}

